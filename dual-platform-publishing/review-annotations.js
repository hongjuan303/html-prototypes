/* Review-only navigation. Number areas and actions, never individual form fields. */
function createReviewAnnotations(frame, notes) {
  let message={}, doc, layer, scheduled=false, points=[], pageKey='', baseMarkup='', contextKey='';
  let openedPlatform='', openedSection='', mainScroll=0;
  const all=(root,selector)=>[...root.querySelectorAll(selector)];
  const first=(root,selector)=>root.querySelector(selector);
  const section=title=>all(notes,'[data-spec-section]').find(el=>el.dataset.specSection===title);
  const group=name=>first(notes,`[data-spec-group="${name}"]`);
  const label=p=>({'抖音':'抖音号','快手':'快手号'}[p]||p);
  const action=name=>`[data-action="${name}"]`;
  const platformScope=p=>`[data-platform-section="${p}"]`;
  const target=(selector,root=doc)=>first(root,selector);
  const representative=(selector)=>all(doc,'.platform-section').map(el=>first(el,selector)).filter(Boolean);
  const fields=(title,names)=>all(section(title)||notes,'[data-spec-field]').filter(el=>names.includes(el.dataset.specField));
  const item=(name,element,hosts)=>({name,element,hosts:(Array.isArray(hosts)?hosts:[hosts]).filter(Boolean)});
  const fromSection=(name,selector,root=doc)=>item(name,section(name),target(selector,root));

  function currentContext(){
    const modal=first(doc,'#overlay:not([hidden]) [role="dialog"]');
    if(!modal)return {key:'page:'+all(doc,'[data-wizard-platform]:checked').map(el=>el.dataset.wizardPlatform).join('|'),modal:null};
    const has=s=>!!first(modal,s),title=modal.getAttribute('aria-label')||'操作说明';
    let kind='other',sections=[];
    if(has('#libraryFilters')){kind='library';sections=['OSS文件库 · 筛选项','OSS文件库 · 列表项','OSS文件库 · 操作']}
    else if(modal.matches('.sync-material-modal')){kind='sync';sections=['同步信息']}
    else if(modal.matches('.ai-title-modal')){kind='ai';sections=['AI生成标题 / 文案']}
    else if(has('#nativeCollectionFilters')){kind='collection';sections=['视频号 · 选择合集']}
    else if(has('[name="assignAccount"], [name="kmAccount"]')){kind='accounts';sections=['选择账号 · 弹窗']}
    else if(has('.cp-draft-editor')){kind='editor';sections=['抖音版权中台 · 编辑素材']}
    else if(has('.cp-retry-form')){kind='editor';sections=['重新提审弹窗']}
    else if(has('#kmEditForm')){kind='editor';sections=['快手经管平台 · 编辑素材']}
    else if(has('.native-material-form')){kind='editor';sections=[label(openedPlatform||message.platform)+' · 编辑素材']}
    else if(has('#configForm')){kind='editor';sections=['模板编辑弹窗']}
    else if(has('#publishInterval, #kmInterval, #confirmBatchPublish, #kmConfirmSubmit')){kind='submit';sections=['发布间隔','提交确认弹窗','版权中台提审']}
    else if(title==='返回发布列表'){kind='confirm';sections=['返回确认']}
    else if(title==='删除视频号发布记录'){kind='confirm';sections=['删除确认']}
    else {sections=[openedSection]}
    return {key:[kind,openedPlatform,title,sections.join('|')].join(':'),kind,modal,title,sections};
  }
  function mainSections(){
    const modalOnly=new Set(['删除确认','重新提审弹窗','选择账号 · 弹窗','视频号 · 选择合集','返回确认','提交确认弹窗','模板编辑弹窗','发布间隔']);
    const selected=all(doc,'[data-wizard-platform]:checked').map(el=>el.dataset.wizardPlatform);
    return all(notes,'[data-spec-section]').filter(el=>{
      const title=el.dataset.specSection;
      if(title.startsWith('OSS文件库')||title.endsWith(' · 编辑素材')||modalOnly.has(title))return false;
      if(message.page==='wizard'&&message.step===2){
        const p=['抖音','视频号','快手','快手经管平台','抖音版权中台'].find(p=>title.startsWith(label(p)+' · '));
        if(p&&!selected.includes(p))return false;
      }
      return true;
    }).map(el=>el.dataset.specSection);
  }
  function showContext(ctx){
    const key=pageKey+'::'+ctx.key;
    if(key===contextKey)return;
    if(contextKey.includes('::page:'))mainScroll=notes.scrollTop;
    notes.innerHTML=baseMarkup;
    const allowed=ctx.modal?ctx.sections:mainSections();
    all(notes,'[data-spec-section]').forEach(el=>el.hidden=!allowed.includes(el.dataset.specSection));
    if(ctx.modal){
      applySpecContext(notes,modalSpecContext(ctx,openedPlatform||message.platform));
      if(ctx.kind==='sync'){
        const keep=label(openedPlatform)+'同步范围';
        fields('同步信息',['抖音号同步范围','视频号同步范围','快手号同步范围']).forEach(el=>el.hidden=el.dataset.specField!==keep);
      }
    }
    all(notes,'[data-spec-group]').forEach(el=>{
      const visible=all(el,':scope > [data-spec-section]').some(part=>!part.hidden);
      let empty=first(el,':scope > .spec-empty');
      if(!empty){empty=notes.ownerDocument.createElement('p');empty.className='spec-empty';el.append(empty)}
      empty.textContent=el.dataset.specGroup==='filters'?'本页无筛选项。':el.dataset.specGroup==='columns'?'本页无列表。':'本页无操作项。';
      empty.hidden=visible;
      // Hide obsolete fallback text generated by the base document.
      all(el,':scope > p:not(.spec-empty)').forEach(p=>p.hidden=true);
      el.hidden=ctx.modal&&!visible;
    });
    first(notes,'.spec-footer').textContent='本页序号从1开始。点击左侧序号可定位对应说明；同一区域内的字段逐项说明。';
    contextKey=key;
    notes.scrollTop=ctx.modal?0:mainScroll;
  }
  function pagePlan(){
    const result=[];
    const add=(title,selector)=>result.push(fromSection(title,selector));
    const area=(name,selector)=>result.push(item(name,group(name==='筛选项'?'filters':'columns'),target(selector)));
    if(message.page==='list'){
      area('筛选项','#filters, #cpFilters, #kmFilters');
      area('列表项','#main .list-panel .table-wrap');
      add('新增发视频',`${action('new')}, ${action('cp-upload')}, ${action('km-new')}`);
      add('继续草稿',action('resume'));
      const title=message.platform==='视频号'?'删除':message.platform==='抖音版权中台'?'编辑与重新提审':'编辑';
      add(title,`${action('delete-video-record')}, ${action('edit-video-record')}, ${action('cp-edit')}`);
      // Selection and pagination are explained under their headings, without extra pins.
    }else if(message.page==='wizard'&&message.step===1){
      area('列表项','#main .table-wrap');
      add('选择素材',action('open-library'));add('移除素材',action('remove-asset'));
      add('保存草稿',action('save-draft'));add('下一步',action('next-step'));add('返回 / 取消',action('exit-wizard'));
    }else if(message.page==='wizard'&&message.step===2){
      result.push(item('列表项',group('columns'),representative('.table-wrap')));
      add('发布平台','.form-line > .field-title');
      result.push(item('选择素材',section('选择素材'),representative(action('platform-library'))));
      result.push(item('AI生成标题 / 文案',section('AI生成标题 / 文案'),representative(action('platform-ai'))));
      result.push(item('选择账号',section('选择账号'),representative(`${action('assign-platform')}, ${action('km-assign-all')}`)));
      result.push(item('编辑素材',section('编辑素材'),representative(`${action('edit-material')}, ${action('km-edit')}, ${action('cp-edit-draft')}`)));
      result.push(item('同步信息',section('同步信息'),representative(`${action('sync-material')}, ${action('km-sync')}, ${action('cp-sync-draft')}`)));
      result.push(item('移除素材',section('移除素材'),representative(`${action('exclude-material')}, ${action('km-remove')}, ${action('cp-remove-asset')}`)));
      add('保存草稿',action('save-draft'));add('上一步',action('previous-step'));add('下一步',action('next-step'));
    }else if(message.page==='wizard'){
      area('列表项','#main .table-wrap');add('提交前校验','#onlyValid');
      add('保存草稿',action('save-draft'));add('上一步',action('previous-step'));add('提交结果',action('submit-task'));
    }else if(message.page==='config'){
      area('列表项','#main .table-wrap');add('新增模板','[data-action="edit-template"]:not([data-id])');
      add('编辑模板','[data-action="edit-template"][data-id]');add('启用 / 停用',action('toggle-config'));
    }else if(message.page==='batch'){
      area('列表项','#main .table-wrap');add('结果处理',action('detail'));
    }
    return result.filter(p=>p.element&&!p.element.closest('[hidden]')&&p.hosts.length);
  }
  function modalPlan(ctx){
    const root=ctx.modal,h=target('.modal-header h2',root),plan=[];
    if(ctx.kind==='library'){
      plan.push(item('筛选项',group('filters'),target('#libraryFilters',root)),item('列表项',group('columns'),target('.table-wrap',root)),item('加入任务',fields('OSS文件库 · 操作',['加入任务'])[0],target('#addLibraryAssets',root)));
    }else if(ctx.kind==='ai'){
      plan.push(item('生成设置',section('AI生成标题 / 文案'),target('.platform-ai-settings',root)));
      const preview=target('.platform-ai-table',root);
      if(preview)plan.push(item('生成结果',fields('AI生成标题 / 文案',['生成结果（可编辑）'])[0],preview));
      plan.push(item('生成预览',fields('AI生成标题 / 文案',['生成预览'])[0],target('#platformAIGenerate',root)));
      plan.push(item('确认应用',fields('AI生成标题 / 文案',['确认应用'])[0],target('#platformAIApply',root)));
    }else if(ctx.kind==='submit'){
      if(target('#publishInterval, #kmInterval',root))plan.push(item('发布间隔',section('发布间隔'),target('.modal-field',root)));
      plan.push(item('确认提交',section('提交确认弹窗'),h));
    }else{
      plan.push(item(ctx.title,section(ctx.sections[0]),h));
    }
    return plan.filter(p=>p.element&&p.hosts.length);
  }
  function numberPoints(plan){
    plan.sort((a,b)=>a.element===b.element?0:a.element.compareDocumentPosition(b.element)&4?-1:1);
    const changed=plan.length!==points.length||plan.some((p,i)=>p.element!==points[i]?.element||p.name!==points[i]?.name);
    points=plan.map((p,i)=>({...p,number:i+1,key:String(i+1)}));
    if(!changed)return;
    all(notes,'.spec-index').forEach(el=>el.remove());
    all(notes,'[id^="spec-point-"]').forEach(el=>el.removeAttribute('id'));
    points.forEach(p=>{
      const heading=first(p.element,':scope > h2, :scope > h3, :scope > dt')||p.element.firstElementChild;
      const badge=notes.ownerDocument.createElement('span');badge.className='spec-index';badge.textContent=p.number;badge.setAttribute('aria-hidden','true');
      heading.prepend(badge);p.element.id='spec-point-'+p.number;
    });
  }
  function jumpTo(p){
    all(notes,'.spec-focused').forEach(el=>el.classList.remove('spec-focused'));
    p.element.classList.add('spec-focused');p.element.tabIndex=-1;
    const layout=notes.closest('.review-layout');
    if(layout){const left=notes.getBoundingClientRect().left-layout.getBoundingClientRect().left+layout.scrollLeft;layout.scrollTo({left:Math.max(0,left+notes.offsetWidth-layout.clientWidth),behavior:'instant'})}
    notes.scrollTo({top:Math.max(0,p.element.getBoundingClientRect().top-notes.getBoundingClientRect().top+notes.scrollTop-20),behavior:'instant'});
    p.element.focus({preventScroll:true});
  }
  function visibleRect(el){
    if(!el?.isConnected||!el.getClientRects().length||el.closest('[hidden]'))return null;
    const win=doc.defaultView,box=el.getBoundingClientRect();
    let left=0,top=0,right=win.innerWidth,bottom=win.innerHeight;
    for(let parent=el.parentElement;parent&&parent!==doc.body;parent=parent.parentElement){
      const style=win.getComputedStyle(parent),r=parent.getBoundingClientRect();if(style.visibility==='hidden')return null;
      if(/auto|scroll|hidden|clip/.test(style.overflowX)){left=Math.max(left,r.left);right=Math.min(right,r.right)}
      if(/auto|scroll|hidden|clip/.test(style.overflowY)){top=Math.max(top,r.top);bottom=Math.min(bottom,r.bottom)}
    }
    if(!box.width||box.left<left-1||box.left+12>right||box.top<top-1||box.top+12>bottom)return null;
    // Test the anchor corner, so tall tables can still be annotated above the fold.
    const hit=doc.elementFromPoint(Math.min(right-1,box.left+12),Math.min(bottom-1,box.top+12));
    if(hit&&!el.contains(hit)&&!hit.contains(el))return null;
    return {left:Math.max(left+1,box.left-7),top:Math.max(top+1,box.top-10)};
  }
  function draw(){
    scheduled=false;if(!doc?.body||!layer?.isConnected)return;
    const ctx=currentContext();showContext(ctx);numberPoints(ctx.modal?modalPlan(ctx):pagePlan());
    all(doc,'#main .annotation-pin').forEach(el=>el.remove());layer.replaceChildren();
    for(const p of points)for(const host of new Set(p.hosts)){
      const rect=visibleRect(host);if(!rect)continue;
      const badge=doc.createElement('button');badge.type='button';badge.className='review-point';badge.dataset.reviewPoint=p.key;badge.textContent=p.number;
      badge.title=`${p.number} · ${p.name}（查看说明）`;badge.setAttribute('aria-label',`查看说明 ${p.number}：${p.name}`);badge.style.left=rect.left+'px';badge.style.top=rect.top+'px';layer.append(badge);
    }
  }
  function schedule(){if(scheduled||!doc)return;scheduled=true;doc.defaultView.requestAnimationFrame(draw)}
  function connect(next){
    if(doc===next)return;doc=next;
    const style=doc.createElement('style');style.textContent='#reviewCallouts{position:fixed;inset:0;z-index:1000;pointer-events:none;overflow:hidden}.review-point{position:absolute;display:grid;place-items:center;width:22px;height:22px;padding:0;min-width:22px;border:2px solid #fff;border-radius:50%;background:#f28c18;color:#fff;box-shadow:0 1px 3px #68390026;font:600 11px/1 -apple-system,BlinkMacSystemFont,"PingFang SC",sans-serif;cursor:pointer;pointer-events:auto}.review-point:hover,.review-point:focus-visible{background:#d97508;outline:2px solid #f28c18;outline-offset:2px}';doc.head.append(style);
    layer=doc.createElement('div');layer.id='reviewCallouts';layer.setAttribute('aria-label','原型说明定位');doc.body.append(layer);
    doc.addEventListener('click',event=>{
      const badge=event.target.closest('[data-review-point]');
      if(badge){event.preventDefault();event.stopImmediatePropagation();const p=points.find(x=>x.key===badge.dataset.reviewPoint);if(p)jumpTo(p);return}
      const trigger=event.target.closest('[data-action]');
      if(trigger){
        const p=points.find(p=>p.hosts.some(host=>host.dataset.action===trigger.dataset.action&&(host.dataset.platform||'')===(trigger.dataset.platform||'')));
        if(p)openedSection=p.element.dataset.specSection||p.name;
        openedPlatform=trigger.dataset.platform||trigger.closest('[data-platform-section]')?.dataset.platformSection||openedPlatform||message.platform||'';
      }
      schedule();
    },true);
    for(const event of ['change','submit','input','keydown','scroll'])doc.addEventListener(event,schedule,true);
    doc.defaultView.addEventListener('resize',schedule);
    // Modal content is replaced by the existing form handlers; observe only the overlay.
    const overlay=first(doc,'#overlay');
    if(overlay)new MutationObserver(schedule).observe(overlay,{childList:true,subtree:true,attributes:true,attributeFilter:['hidden']});
  }
  return {update(next){
    message=next;const key=[message.page,message.step,message.page==='list'?message.platform:''].join(':');
    if(key!==pageKey||!baseMarkup){pageKey=key;baseMarkup=notes.innerHTML;contextKey='';mainScroll=0;openedPlatform=message.platform||'';points=[]}
    const nextDoc=frame.contentDocument;if(!nextDoc?.body?.classList.contains('annotated'))return;connect(nextDoc);draw();
  }};
}
