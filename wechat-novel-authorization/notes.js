function renderNotes(view) {
  const note = pageNotes[view];
  const panel = document.querySelector("#notes");
  panel.innerHTML = `<h2>#页面说明</h2><ul><li>${note.page}</li></ul>
    <h2>#原型说明</h2><ul><li><b>背景：</b>外部小程序需要授权后使用我方微信小说媒资。</li><li><b>需求：</b>${note.goal}</li></ul>
    ${note.groups.map(([title, points, numbered = true], index) => `<section id="note-${index + 1}">
      <h3>${numbered ? `<span class="note-number">${index + 1}</span>` : ""}${title}</h3>
      <ul>${points.map((point) => `<li>${point}</li>`).join("")}</ul>
    </section>`).join("")}`;
  panel.scrollTop = 0;
}

function locateNote(number) {
  document.querySelector(".notes .highlight")?.classList.remove("highlight");
  const section = document.querySelector("#note-" + number);
  section?.classList.add("highlight");
  section?.scrollIntoView({ block: "nearest", inline: "end" });
}
